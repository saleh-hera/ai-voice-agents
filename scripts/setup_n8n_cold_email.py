def main():
    values = run_wizard()

    print("Validating config...")
    ok = True
    ok &= validate("N8N_URL set", bool(values["N8N_URL"]))
    ok &= validate("N8N_API_KEY set", bool(values["N8N_API_KEY"]))
    ok &= validate("CLAUDE_API_KEY set", bool(values["CLAUDE_API_KEY"]))
    ok &= validate("GOOGLE_SHEET_ID set", bool(values["GOOGLE_SHEET_ID"]))
    ok &= validate("GMAIL_FROM looks like an email", "@" in values["GMAIL_FROM"])
    if not ok:
        print("\nFix the missing/invalid values above and re-run.")
        sys.exit(1)

    client = N8nClient(values["N8N_URL"], values["N8N_API_KEY"])

    print("\nTesting n8n connection...")
    try:
        client.test_connection()
        print("  [OK] Connected to n8n API")
    except requests.RequestException as e:
        print(f"  [FAIL] Could not reach n8n at {values['N8N_URL']}: {e}")
        sys.exit(1)

    print("\nCreating credentials...")
    try:
        claude_cred = client.create_credential(
            "Claude API (cold email)",
            "claudeApi",
            {"apiKey": values["CLAUDE_API_KEY"]},
        )
        print("  [OK] Claude API credential created")
    except requests.RequestException as e:
        print(f"  [FAIL] Claude credential creation failed: {e}")
        sys.exit(1)

    try:
        google_cred = client.create_credential(
            "Google OAuth2 (cold email)",
            "googleSheetsOAuth2Api",
            {
                "clientId": values["GOOGLE_OAUTH_CLIENT_ID"],
                "clientSecret": values["GOOGLE_OAUTH_CLIENT_SECRET"],
            },
        )
        print("  [OK] Google OAuth2 credential shell created")
        print(
            "  [ACTION REQUIRED] Open "
            f"{values['N8N_URL'].rstrip('/')}/credentials to click "
            "'Connect my account' for 'Google OAuth2 (cold email)' "
            "(needed for both Sheets and Gmail nodes) -- this step requires "
            "a browser and cannot be automated via the API."
        )
    except requests.RequestException as e:
        print(f"  [FAIL] Google credential creation failed: {e}")
        sys.exit(1)

    print("\nBuilding and deploying workflow...")
    workflow = build_workflow(values)
    try:
        created = client.create_workflow(workflow)
        workflow_id = created["id"]
        print(f"  [OK] Workflow created (id: {workflow_id})")
    except requests.RequestException as e:
        print(f"  [FAIL] Workflow creation failed: {e}")
        sys.exit(1)

    print(
        "\nBefore activating: complete the Google OAuth connection above, "
        "then this script will activate the workflow."
    )
    input("Press Enter once the Google OAuth2 credential shows 'Connected' in n8n...")

    try:
        client.activate_workflow(workflow_id)
        print("  [OK] Workflow activated (cron will fire daily at 9:00 AM)")
    except requests.RequestException as e:
        print(f"  [FAIL] Activation failed: {e}")
        print(
            "  You can activate manually in the n8n editor once the Google "
            "credential is connected."
        )
        sys.exit(1)

    print(
        "\nTo test now with sample data: open the workflow in the n8n editor "
        "and click 'Execute Workflow' -- this exercises the full "
        "Sheets -> Claude -> Gmail -> Sheets chain against one 'Not Sent' row "
        "without waiting for the 9 AM cron."
    )
    print(f"Editor: {values['N8N_URL'].rstrip('/')}/workflow/{workflow_id}")

    print("\n=== Setup complete ===")
    print(f"Workflow ID: {workflow_id}")
    print("Nodes: Cron -> Read Sheet -> Filter -> Claude -> Send Gmail -> Update Sheet")
    print("Error handling: Claude/Gmail failures route to 'Log Error Row' (Status=Error)")


if __name__ == "__main__":
    main()
