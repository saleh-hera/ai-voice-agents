#!/usr/bin/env python3
"""
Interactive wizard that builds the Apollo -> Claude -> Google Sheets -> Gmail
cold-email workflow directly in an n8n instance via its REST API.

Run:
    python scripts/setup_n8n_cold_email.py

Config is read from / saved to scripts/.env (gitignored). Never commit that file.

Notes on Google OAuth2 (Sheets + Gmail):
    n8n's REST API cannot complete an OAuth consent flow on your behalf -
    Google requires an interactive browser redirect. This script creates the
    credential *shells* (client ID/secret) via the API, then prints a link to
    finish "Connect my account" in the n8n editor. Everything else (nodes,
    connections, cron schedule, error handling, activation, test execution)
    is fully automated.
"""
import json
import os
import sys
import time
from pathlib import Path

import requests

SCRIPT_DIR = Path(__file__).resolve().parent
ENV_PATH = SCRIPT_DIR / ".env"

REQUIRED_KEYS = [
    ("N8N_URL", "n8n instance URL (e.g. https://n8n.yourdomain.com)"),
    ("N8N_API_KEY", "n8n API key (n8n UI -> Settings -> API -> Create an API key)"),
    ("CLAUDE_API_KEY", "Claude API key (console.anthropic.com)"),
    ("GOOGLE_OAUTH_CLIENT_ID", "Google OAuth2 client ID (Google Cloud Console)"),
    ("GOOGLE_OAUTH_CLIENT_SECRET", "Google OAuth2 client secret"),
    ("GOOGLE_SHEET_ID", "Google Sheet ID (from the sheet's URL)"),
    ("GMAIL_FROM", "Gmail address to send from"),
]


def load_env():
    values = {}
    if ENV_PATH.exists():
        for line in ENV_PATH.read_text().splitlines():
            line = line.strip()
            if not line or line.startswith("#") or "=" not in line:
                continue
            k, v = line.split("=", 1)
            values[k.strip()] = v.strip()
    return values


def save_env(values):
    lines = ["# Generated by setup_n8n_cold_email.py -- do not commit this file"]
    for key, _ in REQUIRED_KEYS:
        lines.append(f"{key}={values.get(key, '')}")
    ENV_PATH.write_text("\n".join(lines) + "\n")


def prompt(label, existing=None, secret=False):
    suffix = " [keep existing]" if existing else ""
    val = input(f"{label}{suffix}: ").strip()
    if not val and existing:
        return existing
    return val


def run_wizard():
    print("=== n8n Cold Email Workflow Setup Wizard ===\n")
    values = load_env()
    for key, desc in REQUIRED_KEYS:
        values[key] = prompt(desc, values.get(key))
    save_env(values)
    print(f"\nSaved config to {ENV_PATH}\n")
    return values


class N8nClient:
    def __init__(self, base_url, api_key):
        self.base_url = base_url.rstrip("/")
        self.session = requests.Session()
        self.session.headers.update(
            {"X-N8N-API-KEY": api_key, "Content-Type": "application/json"}
        )

    def _url(self, path):
        return f"{self.base_url}/api/v1{path}"

    def test_connection(self):
        r = self.session.get(self._url("/workflows?limit=1"), timeout=15)
        r.raise_for_status()
        return True

    def create_credential(self, name, cred_type, data):
        r = self.session.post(
            self._url("/credentials"),
            json={"name": name, "type": cred_type, "data": data},
            timeout=15,
        )
        r.raise_for_status()
        return r.json()

    def create_workflow(self, workflow):
        r = self.session.post(self._url("/workflows"), json=workflow, timeout=30)
        r.raise_for_status()
        return r.json()

    def activate_workflow(self, workflow_id):
        r = self.session.post(self._url(f"/workflows/{workflow_id}/activate"), timeout=15)
        r.raise_for_status()
        return r.json()

    def list_executions(self, workflow_id, limit=5):
        r = self.session.get(
            self._url(f"/executions?workflowId={workflow_id}&limit={limit}"), timeout=15
        )
        r.raise_for_status()
        return r.json()


def validate(name, cond, hint=""):
    status = "OK" if cond else "FAIL"
    print(f"  [{status}] {name}" + (f" -- {hint}" if hint and not cond else ""))
    return cond


